-- Exports one-time quest reward gear from a VMaNGOS world database (MariaDB) as the body of a Flyway seed migration.
-- One row per (item, quest): an item rewarded by several quests (mostly Alliance/Horde mirrors) keeps every quest,
-- the app decides how to combine them.
--
-- Run (see README.md):
--   docker exec -i mariadb mariadb -N -r -u root mangos < quest_rewards_export.sql > V4__Seed_quest_rewards.sql

WITH
-- 1. quest_template and item_template keep one row per entry *per patch*. Era runs the final data, so keep the
--    newest row per entry. ROW_NUMBER numbers the versions of each entry, newest first.
ranked_quests AS (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY entry ORDER BY patch DESC) AS rn
    FROM quest_template
),
latest_quests AS (
    SELECT * FROM ranked_quests WHERE rn = 1
),
ranked_items AS (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY entry ORDER BY patch DESC) AS rn
    FROM item_template
),
latest_items AS (
    SELECT * FROM ranked_items WHERE rn = 1
),

-- 2. Unpivot: a quest stores its rewards in 10 columns (6 "choose one" + 4 guaranteed). MariaDB has no UNPIVOT, so
--    each column gets its own SELECT, and UNION ALL stacks them into rows. UNION ALL (not UNION) because there is
--    nothing to deduplicate and UNION would pay for a sort to try.
quest_rewards AS (
    SELECT entry AS quest_id, RewChoiceItemId1 AS item_id, 'CHOICE' AS reward_kind FROM latest_quests
    UNION ALL SELECT entry, RewChoiceItemId2, 'CHOICE' FROM latest_quests
    UNION ALL SELECT entry, RewChoiceItemId3, 'CHOICE' FROM latest_quests
    UNION ALL SELECT entry, RewChoiceItemId4, 'CHOICE' FROM latest_quests
    UNION ALL SELECT entry, RewChoiceItemId5, 'CHOICE' FROM latest_quests
    UNION ALL SELECT entry, RewChoiceItemId6, 'CHOICE' FROM latest_quests
    UNION ALL SELECT entry, RewItemId1, 'GUARANTEED' FROM latest_quests
    UNION ALL SELECT entry, RewItemId2, 'GUARANTEED' FROM latest_quests
    UNION ALL SELECT entry, RewItemId3, 'GUARANTEED' FROM latest_quests
    UNION ALL SELECT entry, RewItemId4, 'GUARANTEED' FROM latest_quests
),

-- 3. Keep gear only, rewarded by quests that can be done once:
--    - item_id 0 is an empty reward slot
--    - class 2 = weapon, 4 = armor; inventory_type 0 = not equippable, 4 = shirt, 19 = tabard
--    - bonding 1 = binds when picked up. BoE rewards can be traded, so a second copy is obtainable
--    - SpecialFlags bit 1 = repeatable (removes nothing in the current snapshot, kept as a guard)
one_time_gear_rewards AS (
    SELECT i.entry           AS base_id,
           q.entry           AS quest_id,
           q.MinLevel        AS quest_min_level,
           q.QuestLevel      AS quest_level,
           r.reward_kind,
           q.RequiredClasses AS required_classes,
           q.RequiredRaces   AS required_races
    FROM quest_rewards r
             JOIN latest_quests q ON q.entry = r.quest_id
             JOIN latest_items i ON i.entry = r.item_id
    WHERE r.item_id <> 0
      AND i.class IN (2, 4)
      AND i.inventory_type NOT IN (0, 4, 19)
      AND i.bonding = 1
      AND (q.SpecialFlags & 1) = 0
),

-- 4. Render as one multi-row INSERT. COUNT(*) OVER () is the total row count on every row, so the last row can end
--    with ';' instead of ','.
numbered AS (
    SELECT r.*,
           ROW_NUMBER() OVER (ORDER BY base_id, quest_id) AS line_no,
           COUNT(*) OVER ()                               AS line_count
    FROM one_time_gear_rewards r
)
SELECT line
FROM (
    SELECT 0 AS line_no,
           CONCAT('-- Generated by tools/vmangos-export/quest_rewards_export.sql from a VMaNGOS world database\n',
                  '-- (https://github.com/vmangos/core, GPL-2.0). World of Warcraft data (c) Blizzard Entertainment.\n',
                  'INSERT INTO quest_rewards (base_id, quest_id, quest_min_level, quest_level, reward_kind, ',
                  'required_classes, required_races)\nVALUES') AS line
    UNION ALL
    SELECT line_no,
           CONCAT('    (', base_id, ', ', quest_id, ', ', quest_min_level, ', ', quest_level, ', ''', reward_kind,
                  ''', ', required_classes, ', ', required_races, ')',
                  IF(line_no = line_count, ';', ','))
    FROM numbered
) AS rendered
ORDER BY line_no;
